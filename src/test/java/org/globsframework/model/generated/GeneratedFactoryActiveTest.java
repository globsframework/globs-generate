    private GlobType build(String name, int count) {
        GlobTypeBuilder b = GlobTypeBuilderFactory.create(name);
        for (int i = 0; i < count; i++) {
            switch (i % 3) {
                case 0 -> b.declareStringField("s" + i);
                case 1 -> b.declareIntegerField("i" + i);
                default -> b.declareDoubleField("d" + i);
            }
        }
        return b.build();
    }

    private MutableGlob instantiate(String service, String typeName, int count) {
        System.setProperty("globs.builder", service);
        GlobFactoryService.Builder.reset();
        return build(typeName, count).instantiate();
    }

