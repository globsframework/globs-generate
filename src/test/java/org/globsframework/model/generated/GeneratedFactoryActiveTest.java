    /**
     * The VisitorUnrollPerf benchmark compares GlobSerializer (which loops over type.getFields() itself)
     * against the same writes driven by glob.accept. That comparison is only meaningful if both emit the
     * same bytes for a fully populated glob.
     */
    @Test
    public void serializingThroughAcceptEmitsTheSameBytes() {
        MutableGlob glob = instantiate("org.globsframework.model.generator.object.GeneratorGlobFactoryService",
                "ActiveBytes", 12);
        for (Field field : glob.getType().getFields()) {
            if (field instanceof StringField f) {
                glob.set(f, "value" + field.getIndex());
            } else if (field instanceof IntegerField f) {
                glob.set(f, field.getIndex());
            } else if (field instanceof DoubleField f) {
                glob.set(f, field.getIndex() * 1.5);
            }
        }

        ByteBufferSerializationOutput viaLoop = new ByteBufferSerializationOutput(new byte[4096]);
        new GlobSerializer(viaLoop).writeKnowGlob(glob);

        ByteBufferSerializationOutput viaAccept = new ByteBufferSerializationOutput(new byte[4096]);
        SerializingVisitor visitor = new SerializingVisitor();
        visitor.output = viaAccept;
        glob.safeAccept(visitor);

        Assertions.assertEquals(viaLoop.position(), viaAccept.position());
        Assertions.assertArrayEquals(Arrays.copyOf(viaLoop.getBuffer(), viaLoop.position()),
                Arrays.copyOf(viaAccept.getBuffer(), viaAccept.position()));
    }

    /**
     * checkGetSet only covers Integer/Double/Long. Every other kind of accessor built by
     * AbstractGeneratedGlobFactory is exercised here : set through the typed accessor, read back through
     * the get accessor, on a really generated Glob.
     */
    @Test
    public void everyAccessorKindRoundTrips() {
        for (String service : new String[]{
                "org.globsframework.model.generator.object.GeneratorGlobFactoryService",
                "org.globsframework.model.generator.primitive.GeneratorGlobFactoryService"}) {
            System.setProperty("globs.builder", service);
            GlobFactoryService.Builder.reset();

            GlobTypeBuilder target = GlobTypeBuilderFactory.create("AccTarget" + service.hashCode());
            target.declareStringField("name");
            GlobType targetType = target.build();

            GlobTypeBuilder b = GlobTypeBuilderFactory.create("AccAll" + service.hashCode());
            StringField str = b.declareStringField("str");
            StringArrayField strArray = b.declareStringArrayField("strArray");
            BooleanField bool = b.declareBooleanField("bool");
            BooleanArrayField boolArray = b.declareBooleanArrayField("boolArray");
            IntegerArrayField intArray = b.declareIntegerArrayField("intArray");
            DoubleArrayField doubleArray = b.declareDoubleArrayField("doubleArray");
            LongArrayField longArray = b.declareLongArrayField("longArray");
            BigDecimalField bigDecimal = b.declareBigDecimalField("bigDecimal");
            BigDecimalArrayField bigDecimalArray = b.declareBigDecimalArrayField("bigDecimalArray");
            DateField date = b.declareDateField("date");
            DateTimeField dateTime = b.declareDateTimeField("dateTime");
            BytesField bytes = b.declareBytesField("bytes");
            GlobField<?> globField = b.declareGlobField("glob", () -> targetType);
            GlobArrayField<?> globArray = b.declareGlobArrayField("globArray", () -> targetType);
            GlobType type = b.build();

            MutableGlob glob = type.instantiate();
            Assertions.assertTrue(glob.getClass().getName().startsWith("org.globsframework.gen."),
                    "not a generated glob : " + glob.getClass().getName());

            Glob child = targetType.instantiate().set(targetType.getField("name").asStringField(), "child");
            Object[] values = {
                    "text", new String[]{"a", "b"}, Boolean.TRUE, new boolean[]{true, false},
                    new int[]{1, 2}, new double[]{1.5, 2.5}, new long[]{7L, 8L},
                    new java.math.BigDecimal("1.25"), new java.math.BigDecimal[]{new java.math.BigDecimal("2.5")},
                    java.time.LocalDate.of(2026, 8, 2),
                    java.time.ZonedDateTime.of(2026, 8, 2, 10, 0, 0, 0, java.time.ZoneId.of("UTC")),
                    new byte[]{1, 2, 3}, child, new Glob[]{child}
            };
            Field[] fields = {str, strArray, bool, boolArray, intArray, doubleArray, longArray,
                    bigDecimal, bigDecimalArray, date, dateTime, bytes, globField, globArray};

            for (int i = 0; i < fields.length; i++) {
                Field field = fields[i];
                Assertions.assertTrue(type.getGlobFactory().getGetValueAccessor(field).getClass().getName()
                                .startsWith("org.globsframework.gen."),
                        field.getName() + " get accessor is not generated : "
                        + type.getGlobFactory().getGetValueAccessor(field).getClass().getName());
                Assertions.assertTrue(type.getGlobFactory().getSetValueAccessor(field).getClass().getName()
                                .startsWith("org.globsframework.gen."),
                        field.getName() + " set accessor is not generated : "
                        + type.getGlobFactory().getSetValueAccessor(field).getClass().getName());
                type.getGlobFactory().getSetValueAccessor(field).setValue(glob, values[i]);
                Object read = type.getGlobFactory().getGetValueAccessor(field).getValue(glob);
                Assertions.assertTrue(type.getGlobFactory().getGetValueAccessor(field).isSet(glob),
                        field.getName() + " should be set (" + service + ")");
                Assertions.assertFalse(type.getGlobFactory().getGetValueAccessor(field).isNull(glob),
                        field.getName() + " should not be null (" + service + ")");
                Assertions.assertTrue(field.valueEqual(values[i], read),
                        field.getName() + " round trip failed on " + service + " : got " + read);
            }

            for (Field field : fields) {
                type.getGlobFactory().getSetValueAccessor(field).setValue(glob, null);
                Assertions.assertTrue(type.getGlobFactory().getGetValueAccessor(field).isNull(glob),
                        field.getName() + " should be null after set(null) on " + service);
            }
        }
    }

    /**
     * accept(FieldValueVisitorWithContext, CTX) used to be missing altogether from the object flavour :
     * calling it threw AbstractMethodError. It must visit exactly the set fields, forward the context, and
     * give the same result unrolled (generated) or looped (base class).
     */
    @Test
    public void acceptWithContextVisitsTheSetFieldsOnly() {
        for (String service : new String[]{
                "org.globsframework.model.generator.object.GeneratorGlobFactoryService",
                "org.globsframework.model.generator.primitive.GeneratorGlobFactoryService"}) {
            for (int fieldCount : new int[]{9, 45}) {
                String tag = service.contains("object") ? "Obj" : "Prim";
                MutableGlob glob = instantiate(service, "Ctx" + tag + fieldCount, fieldCount);
                Assertions.assertTrue(glob.getClass().getName().startsWith("org.globsframework.gen."),
                        "not generated : " + glob.getClass().getName());

                if (service.contains("object")) {
                    // the object flavour generates it unrolled : it must be declared on the generated class,
                    // not inherited from the looped fallback of AbstractGeneratedGlob32/64
                    Assertions.assertDoesNotThrow(() -> glob.getClass().getDeclaredMethod(
                                    "accept", FieldValueVisitorWithContext.class, Object.class),
                            "unrolled accept(visitor, ctx) not generated on " + glob.getClass().getName());
                }

                Field[] fields = glob.getType().getFields();
                glob.setValue(fields[0], "s0");
                glob.setValue(fields[1], 11);
                glob.setValue(fields[fields.length - 1], expectedFor(fields[fields.length - 1]));

                StringBuilder context = new StringBuilder();
                CollectingVisitor visitor = new CollectingVisitor();
                Assertions.assertSame(visitor, glob.safeAccept(visitor, context),
                        "accept must hand the visitor back");

                String expected = fields[0].getName() + "=s0;" + fields[1].getName() + "=11;"
                                  + fields[fields.length - 1].getName() + "="
                                  + expectedFor(fields[fields.length - 1]) + ";";
                Assertions.assertEquals(expected, context.toString(),
                        "accept(visitor, ctx) on " + service + " with " + fieldCount + " fields");
            }
        }
    }

    private Object expectedFor(Field field) {
        if (field instanceof StringField) {
            return "last";
        }
        return field instanceof IntegerField ? 99 : 9.5;
    }

    /** The visitor receives the context as third argument and appends to it, so nothing is static. */
    static class CollectingVisitor implements FieldValueVisitorWithContext<StringBuilder> {
        public void visitInteger(IntegerField field, Integer value, StringBuilder ctx) {
            append(field, value, ctx);
        }

        public void visitDouble(DoubleField field, Double value, StringBuilder ctx) {
            append(field, value, ctx);
        }

        public void visitString(StringField field, String value, StringBuilder ctx) {
            append(field, value, ctx);
        }

        private void append(Field field, Object value, StringBuilder ctx) {
            ctx.append(field.getName()).append('=').append(value).append(';');
        }

        public void visitIntegerArray(IntegerArrayField field, int[] value, StringBuilder ctx) { fail(field); }
        public void visitDoubleArray(DoubleArrayField field, double[] value, StringBuilder ctx) { fail(field); }
        public void visitBigDecimal(BigDecimalField field, java.math.BigDecimal value, StringBuilder ctx) { fail(field); }
        public void visitBigDecimalArray(BigDecimalArrayField field, java.math.BigDecimal[] value, StringBuilder ctx) { fail(field); }
        public void visitStringArray(StringArrayField field, String[] value, StringBuilder ctx) { fail(field); }
        public void visitBoolean(BooleanField field, Boolean value, StringBuilder ctx) { fail(field); }
        public void visitBooleanArray(BooleanArrayField field, boolean[] value, StringBuilder ctx) { fail(field); }
        public void visitLong(LongField field, Long value, StringBuilder ctx) { fail(field); }
        public void visitLongArray(LongArrayField field, long[] value, StringBuilder ctx) { fail(field); }
        public void visitDate(DateField field, java.time.LocalDate value, StringBuilder ctx) { fail(field); }
        public void visitDateTime(DateTimeField field, java.time.ZonedDateTime value, StringBuilder ctx) { fail(field); }
        public void visitBytes(BytesField field, byte[] value, StringBuilder ctx) { fail(field); }
        public void visitGlob(GlobField<?> field, Glob value, StringBuilder ctx) { fail(field); }
        public void visitGlobArray(GlobArrayField<?> field, Glob[] value, StringBuilder ctx) { fail(field); }
        public void visitUnionGlob(GlobUnionField field, Glob value, StringBuilder ctx) { fail(field); }
        public void visitUnionGlobArray(GlobArrayUnionField field, Glob[] value, StringBuilder ctx) { fail(field); }

        private void fail(Field field) {
            throw new IllegalStateException("unset field visited : " + field.getName());
        }
    }

    /**
     * The three GlobFactory.accept overloads, generated unrolled on the factory. They walk the fields of the
     * type (not the values of a Glob), so all of them must visit every field, in index order, and forward
     * the contexts untouched.
     */
    @Test
    public void factoryAcceptsVisitEveryFieldInOrder() throws Exception {
        for (String service : new String[]{
                "org.globsframework.model.generator.object.GeneratorGlobFactoryService",
                "org.globsframework.model.generator.primitive.GeneratorGlobFactoryService"}) {
            String tag = service.contains("object") ? "Obj" : "Prim";
            System.setProperty("globs.builder", service);
            GlobFactoryService.Builder.reset();
            GlobType type = build("FactAccept" + tag, 7);
            GlobFactory factory = type.getGlobFactory();

            // otherwise the GlobFactory default methods would answer and this test would prove nothing
            for (Class<?>[] params : new Class<?>[][]{
                    {FieldVisitor.class},
                    {FieldVisitorWithContext.class, Object.class},
                    {FieldVisitorWithTwoContext.class, Object.class, Object.class}}) {
                Assertions.assertDoesNotThrow(() -> factory.getClass().getDeclaredMethod("accept", params),
                        "accept" + java.util.Arrays.toString(params) + " not generated on "
                        + factory.getClass().getName());
            }

            String expected = String.join(",", java.util.Arrays.stream(type.getFields())
                    .map(Field::getName).toList());

            StringBuilder plain = new StringBuilder();
            factory.accept(new FieldVisitor.AbstractFieldVisitor() {
                public void notManaged(Field field) {
                    plain.append(plain.isEmpty() ? "" : ",").append(field.getName());
                }
            });
            Assertions.assertEquals(expected, plain.toString(), "accept(visitor) on " + service);

            StringBuilder one = new StringBuilder();
            StringBuilder returnedContext = new StringBuilder();
            factory.accept(new FieldVisitorWithContext.AbstractFieldVisitor<StringBuilder>() {
                public void notManaged(Field field, StringBuilder ctx) {
                    Assertions.assertSame(one, ctx, "the context must be forwarded as is");
                    ctx.append(ctx.isEmpty() ? "" : ",").append(field.getName());
                }
            }, one);
            Assertions.assertEquals(expected, one.toString(), "accept(visitor, ctx) on " + service);
            Assertions.assertTrue(returnedContext.isEmpty());

            StringBuilder first = new StringBuilder();
            StringBuilder second = new StringBuilder();
            factory.accept(new FieldVisitorWithTwoContext.AbstractFieldVisitor<StringBuilder, StringBuilder>() {
                public void notManaged(Field field, StringBuilder ctx1, StringBuilder ctx2) {
                    Assertions.assertSame(first, ctx1, "first context must be forwarded as is");
                    Assertions.assertSame(second, ctx2, "second context must be forwarded as is");
                    ctx1.append(ctx1.isEmpty() ? "" : ",").append(field.getName());
                    ctx2.append(field.getIndex());
                }
            }, first, second);
            Assertions.assertEquals(expected, first.toString(), "accept(visitor, c1, c2) on " + service);
            Assertions.assertEquals("0123456", second.toString(), "second context on " + service);
        }
    }

    /**
     * Both flavours now emit the three unrolled visitors, so both must visit exactly the set fields, with
     * the same values doGet would return — including the fields that are set *to null*, which is the case
     * the primitive flavour has to read out of its isNull mask. Checked on both mask widths.
     * <p>
     * The declared-method assertions are the point : a wrong descriptor would leave the interface default
     * in place, the visited list would still come out right, and nothing would tell us the generated
     * methods are dead.
     */
    @Test
    public void bothFlavoursEmitUnrolledVisitorsThatVisitTheSetFields() throws Exception {
        for (String service : new String[]{
                "org.globsframework.model.generator.object.GeneratorGlobFactoryService",
                "org.globsframework.model.generator.primitive.GeneratorGlobFactoryService"}) {
            for (int fieldCount : new int[]{9, 45}) {
                String tag = service.contains("object") ? "Obj" : "Prim";
                MutableGlob glob = instantiate(service, "Unroll" + tag + fieldCount, fieldCount);
                GlobType type = glob.getType();
                Class<?> globClass = glob.getClass();

                Assertions.assertDoesNotThrow(() -> globClass.getDeclaredMethod("accept", FieldValueVisitor.class),
                        "accept(FieldValueVisitor) is not generated on " + service);
                Assertions.assertDoesNotThrow(
                        () -> globClass.getDeclaredMethod("accept", FieldValueVisitorWithContext.class, Object.class),
                        "accept(FieldValueVisitorWithContext, CTX) is not generated on " + service);
                Assertions.assertDoesNotThrow(
                        () -> globClass.getDeclaredMethod("apply", FieldValues.Functor.class),
                        "apply(Functor) is not generated on " + service);

                // a value, an explicit null and an untouched field, so all three states are covered
                for (Field field : type.getFields()) {
                    switch (field.getIndex() % 3) {
                        case 0 -> type.getGlobFactory().getSetValueAccessor(field).setValue(glob, valueFor(field));
                        case 1 -> type.getGlobFactory().getSetValueAccessor(field).setValue(glob, null);
                        default -> {
                        }
                    }
                }

                StringBuilder expected = new StringBuilder();
                for (Field field : type.getFields()) {
                    if (glob.isSet(field)) {
                        expected.append(field.getName()).append('=')
                                .append(((AbstractGlob) glob).doGet(field)).append(' ');
                    }
                }

                StringBuilder visited = new StringBuilder();
                glob.safeAccept(new FieldValueVisitor.AbstractFieldValueVisitor() {
                    public void notManaged(Field field, Object value) {
                        visited.append(field.getName()).append('=').append(value).append(' ');
                    }
                });
                Assertions.assertEquals(expected.toString(), visited.toString(),
                        "accept on " + service + " / " + fieldCount + " fields");

                StringBuilder applied = new StringBuilder();
                glob.safeApply((field, value) -> applied.append(field.getName()).append('=').append(value).append(' '));
                Assertions.assertEquals(expected.toString(), applied.toString(),
                        "apply on " + service + " / " + fieldCount + " fields");

                StringBuilder withContext = new StringBuilder();
                StringBuilder context = new StringBuilder("ctx");
                glob.safeAccept(new FieldValueVisitorWithContext.AbstractFieldValueVisitor<StringBuilder>() {
                    public void notManaged(Field field, Object value, StringBuilder ctx) {
                        Assertions.assertSame(context, ctx, "the context must be forwarded as is");
                        withContext.append(field.getName()).append('=').append(value).append(' ');
                    }
                }, context);
                Assertions.assertEquals(expected.toString(), withContext.toString(),
                        "accept(visitor, ctx) on " + service + " / " + fieldCount + " fields");
            }
        }
    }

    /**
     * The generated get accessors answer isSet / isNull with a mask read at a constant index instead of
     * inheriting the field.getIndex() (and, for isNull, boxing doGet) versions of
     * AbstractGeneratedGetAccessor. They must agree with the Glob itself in every state, on both mask
     * widths — 10 fields uses the int mask, 45 the long one.
     */
    @Test
    public void generatedIsSetAndIsNullAgreeWithTheGlob() {
        for (String service : new String[]{
                "org.globsframework.model.generator.object.GeneratorGlobFactoryService",
                "org.globsframework.model.generator.primitive.GeneratorGlobFactoryService"}) {
            for (int fieldCount : new int[]{10, 45}) {
                String tag = service.contains("object") ? "Obj" : "Prim";
                MutableGlob glob = instantiate(service, "Mask" + tag + fieldCount, fieldCount);
                GlobType type = glob.getType();
                Assertions.assertTrue(glob.getClass().getName().startsWith("org.globsframework.gen."),
                        "not generated : " + glob.getClass().getName());

                for (Field field : type.getFields()) {
                    Class<?> accessor = type.getGlobFactory().getGetValueAccessor(field).getClass();
                    Assertions.assertTrue(accessor.getName().startsWith("org.globsframework.gen."),
                            field.getName() + " get accessor is not generated");
                    // declared, not inherited : otherwise the mask versions are silently not the ones running
                    Assertions.assertDoesNotThrow(() -> accessor.getDeclaredMethod("isSet", Glob.class),
                            field.getName() + " isSet is inherited, not generated");
                    Assertions.assertDoesNotThrow(() -> accessor.getDeclaredMethod("isNull", Glob.class),
                            field.getName() + " isNull is inherited, not generated");
                }

                // never set
                assertMaskAgrees(glob, "fresh " + tag + fieldCount);

                // set to a real value, one field at a time so the neighbouring bits are checked too
                for (Field field : type.getFields()) {
                    type.getGlobFactory().getSetValueAccessor(field).setValue(glob, valueFor(field));
                    assertMaskAgrees(glob, "after set " + field.getName() + " " + tag + fieldCount);
                }

                // set, but null
                for (Field field : type.getFields()) {
                    type.getGlobFactory().getSetValueAccessor(field).setValue(glob, null);
                    assertMaskAgrees(glob, "after set null " + field.getName() + " " + tag + fieldCount);
                }

                // set again, then unset : set bit off, and null again
                for (Field field : type.getFields()) {
                    type.getGlobFactory().getSetValueAccessor(field).setValue(glob, valueFor(field));
                    glob.unset(field);
                    assertMaskAgrees(glob, "after unset " + field.getName() + " " + tag + fieldCount);
                }
            }
        }
    }

    private Object valueFor(Field field) {
        if (field instanceof StringField) {
            return "v" + field.getIndex();
        }
        if (field instanceof IntegerField) {
            return field.getIndex();
        }
        return field.getIndex() * 1.5;
    }

    /** doGet == null is exactly what the inherited isNull used to answer, so it is the oracle here. */
    private void assertMaskAgrees(Glob glob, String state) {
        for (Field field : glob.getType().getFields()) {
            GlobGetAccessor accessor = glob.getType().getGlobFactory().getGetValueAccessor(field);
            Assertions.assertEquals(glob.isSet(field), accessor.isSet(glob),
                    "isSet(" + field.getName() + ") " + state);
            Assertions.assertEquals(((AbstractGlob) glob).doGet(field) == null, accessor.isNull(glob),
                    "isNull(" + field.getName() + ") " + state);
        }
    }

    /**
     * The generated factory reads its GlobType from AsmGlob*Generator.getType(id) in its {@code <clinit>}.
     * That replaced a single static TYPE slot, which forced create to be synchronized ; this pins that two
     * types generated at the same time each end up wired to their own.
     */
    @Test
    public void concurrentGenerationWiresEachFactoryToItsOwnType() throws Exception {
        for (String service : new String[]{
                "org.globsframework.model.generator.object.GeneratorGlobFactoryService",
                "org.globsframework.model.generator.primitive.GeneratorGlobFactoryService"}) {
            System.setProperty("globs.builder", service);
            GlobFactoryService.Builder.reset();

            int threads = 8;
            String tag = service.contains("object") ? "Obj" : "Prim";
            ExecutorService executor = Executors.newFixedThreadPool(threads);
            CyclicBarrier barrier = new CyclicBarrier(threads);
            List<Future<GlobType>> futures = new ArrayList<>();
            try {
                for (int i = 0; i < threads; i++) {
                    int fieldCount = 3 + i;
                    String name = "Concurrent" + tag + i;
                    futures.add(executor.submit(() -> {
                        barrier.await();
                        return build(name, fieldCount);
                    }));
                }
                for (int i = 0; i < threads; i++) {
                    GlobType type = futures.get(i).get();
                    Assertions.assertEquals("Concurrent" + tag + i, type.getName());
                    Assertions.assertEquals(3 + i, type.getFieldCount());

                    MutableGlob glob = type.instantiate();
                    Assertions.assertTrue(glob.getClass().getName().startsWith("org.globsframework.gen."),
                            "not generated : " + glob.getClass().getName());
                    // the factory's own view of the type, straight out of <clinit>
                    Assertions.assertSame(type, glob.getType());
                    Assertions.assertSame(type, type.getGlobFactory().getGlobType());

                    // and the per-field static constants resolved from it
                    StringBuilder visited = new StringBuilder();
                    type.getGlobFactory().accept(new FieldVisitor.AbstractFieldVisitor() {
                        public void notManaged(Field field) {
                            Assertions.assertSame(type, field.getGlobType());
                            visited.append(field.getName()).append(' ');
                        }
                    });
                    Assertions.assertEquals(Arrays.stream(type.getFields()).map(Field::getName)
                            .collect(Collectors.joining(" ", "", " ")), visited.toString());
                }
            } finally {
                executor.shutdownNow();
            }
        }
    }

    static class SerializingVisitor extends FieldValueVisitor.AbstractFieldValueVisitor {
        SerializedOutput output;

        public void visitString(StringField field, String value) {
            output.writeUtf8String(value);
        }

        public void visitInteger(IntegerField field, Integer value) {
            output.writeInteger(value);
        }

        public void visitDouble(DoubleField field, Double value) {
            output.writeDouble(value);
        }

        public void notManaged(Field field, Object value) {
            throw new IllegalStateException("unexpected field " + field);
        }
    }
