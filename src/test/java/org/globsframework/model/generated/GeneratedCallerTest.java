package org.globsframework.model.generated;

import org.globsframework.core.metamodel.GlobType;
import org.globsframework.core.metamodel.GlobTypeBuilder;
import org.globsframework.core.metamodel.GlobTypeBuilderFactory;
import org.globsframework.core.metamodel.fields.Field;
import org.globsframework.core.model.GlobFactory;
import org.globsframework.core.model.GlobFactoryService;
import org.globsframework.core.model.MutableGlob;
import org.globsframework.model.generator.DefaultFunctionCaller;
import org.globsframework.model.generator.FieldValueFunction;
import org.globsframework.model.generator.GenerateCaller;
import org.globsframework.model.generator.GeneratedFunctionCaller;
import org.globsframework.model.generator.GlobGenerateFactory;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.Test;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.stream.Collectors;
import java.util.stream.IntStream;

/**
 * The caller generated by GenerateCaller : one static final FieldValueFunction per field, called with the
 * same isSet / isNull / value the Glob itself answers.
 * <p>
 * Both flavours and both mask widths, because the isSet and isNull expressions are emitted per flavour and
 * per width — and once per field, so a wrong shift is a wrong answer for one field only.
 */
public class GeneratedCallerTest {
    private static final String OBJECT = "org.globsframework.model.generator.object.GeneratorGlobFactoryService";
    private static final String PRIMITIVE = "org.globsframework.model.generator.primitive.GeneratorGlobFactoryService";

    @AfterEach
    public void tearDown() {
        System.clearProperty("globs.builder");
        GlobFactoryService.Builder.reset();
    }

    /**
     * What one call looked like, in the order the functions were called. ctx1 is not recorded : it is the
     * list these are collected in, so the collecting is the proof that it was forwarded.
     */
    private record Seen(String field, boolean isSet, boolean isNull, Object value, Object ctx2) {
    }

    /** One function per field, each recording into the list it closes over : a distinct class per field. */
    private static GenerateCaller.GetFieldValueFunction<List<Seen>, String> recorder() {
        return new GenerateCaller.GetFieldValueFunction<>() {
            public <T> FieldValueFunction<T, List<Seen>, String> create(Field field) {
                String name = field.getName();
                return (isSet, isNull, value, ctx1, ctx2) ->
                        ctx1.add(new Seen(name, isSet, isNull, value, ctx2));
            }
        };
    }

    private GlobType build(String service, String name, int count) {
        if (service == null) {
            System.clearProperty("globs.builder");
        } else {
            System.setProperty("globs.builder", service);
        }
        GlobFactoryService.Builder.reset();
        GlobTypeBuilder builder = GlobTypeBuilderFactory.create(name);
        for (int i = 0; i < count; i++) {
            switch (i % 4) {
                case 0 -> builder.declareStringField("s" + i);
                case 1 -> builder.declareIntegerField("i" + i);
                case 2 -> builder.declareDoubleField("d" + i);
                default -> builder.declareLongField("l" + i);
            }
        }
        return builder.build();
    }

    private GeneratedFunctionCaller<List<Seen>, String> callerOf(GlobType type) {
        GlobFactory factory = type.getGlobFactory();
        Assertions.assertInstanceOf(GlobGenerateFactory.class, factory,
                "the generated factory is the way in : " + factory.getClass().getName());
        return ((GlobGenerateFactory) factory).create(recorder());
    }

    private List<Seen> call(GeneratedFunctionCaller<List<Seen>, String> caller, MutableGlob glob) {
        List<Seen> seen = new ArrayList<>();
        caller.call(glob, seen, "ctx2");
        return seen;
    }

    private Seen of(List<Seen> seen, String field) {
        return seen.stream().filter(s -> s.field().equals(field)).findFirst()
                .orElseThrow(() -> new AssertionError(field + " was not visited"));
    }

    /**
     * The three states a field can be in, on a type of {@code count} fields : a value, an explicit null and
     * untouched. Unlike the visitors, the caller is called for every field whatever its state.
     */
    private void checkStates(String service, String name, int count) {
        GlobType type = build(service, name, count);
        checkStates(type, callerOf(type), count);
    }

    private void checkStates(GlobType type, GeneratedFunctionCaller<List<Seen>, String> caller, int count) {
        MutableGlob glob = type.instantiate();
        glob.setValue(type.getField("s0"), "hello");
        glob.setValue(type.getField("i1"), 12);
        glob.setValue(type.getField("d2"), null);
        Field last = type.getFields()[count - 1];
        glob.setValue(last, null);

        List<Seen> seen = call(caller, glob);
        Assertions.assertEquals(count, seen.size());
        Assertions.assertEquals(
                Arrays.stream(type.getFields()).map(Field::getName).collect(Collectors.toList()),
                seen.stream().map(Seen::field).collect(Collectors.toList()),
                "the fields are visited in their index order");

        Assertions.assertEquals(new Seen("s0", true, false, "hello", "ctx2"), of(seen, "s0"));
        Assertions.assertEquals(new Seen("i1", true, false, 12, "ctx2"), of(seen, "i1"));
        Assertions.assertEquals(new Seen("d2", true, true, null, "ctx2"), of(seen, "d2"));
        Assertions.assertEquals(new Seen(last.getName(), true, true, null, "ctx2"), of(seen, last.getName()));

        // everything else was never touched : not set, and null like doGet answers
        for (Seen s : seen) {
            if (!List.of("s0", "i1", "d2", last.getName()).contains(s.field())) {
                Assertions.assertFalse(s.isSet(), s.field() + " should not be set");
                Assertions.assertTrue(s.isNull(), s.field() + " should be null");
                Assertions.assertNull(s.value(), s.field() + " should have no value");
            }
        }
    }

    @Test
    public void objectFlavourOnBothMaskWidths() {
        checkStates(OBJECT, "CallerObj32", 10);
        checkStates(OBJECT, "CallerObj64", 45);
    }

    @Test
    public void primitiveFlavourOnBothMaskWidths() {
        checkStates(PRIMITIVE, "CallerPrim32", 10);
        checkStates(PRIMITIVE, "CallerPrim64", 45);
    }

    /**
     * The two ways a type can have no generated Glob class : the module not installed at all, and a type
     * too wide for the generators. callerFor must answer the looped caller for both, so that a caller of
     * this API never carries a second code path.
     */
    @Test
    public void typesWithoutAGeneratedClassFallBackToTheLoopedCaller() {
        GlobType none = build(null, "CallerNoBuilder", 10);
        Assertions.assertFalse(none.getGlobFactory() instanceof GlobGenerateFactory);
        GeneratedFunctionCaller<List<Seen>, String> caller = GenerateCaller.callerFor(none, recorder());
        Assertions.assertInstanceOf(DefaultFunctionCaller.class, caller);
        checkStates(none, caller, 10);

        // above 64 fields both generators hand the type back to core
        GlobType tooWide = build(OBJECT, "CallerTooWide", 70);
        Assertions.assertFalse(tooWide.getGlobFactory() instanceof GlobGenerateFactory);
        GeneratedFunctionCaller<List<Seen>, String> wideCaller = GenerateCaller.callerFor(tooWide, recorder());
        Assertions.assertInstanceOf(DefaultFunctionCaller.class, wideCaller);
        checkStates(tooWide, wideCaller, 70);
    }

    /** ... and the generated one whenever there is one. */
    @Test
    public void callerForPrefersTheGeneratedCaller() {
        for (String service : List.of(OBJECT, PRIMITIVE)) {
            GlobType type = build(service, "CallerForGen" + service.hashCode(), 10);
            GeneratedFunctionCaller<List<Seen>, String> caller = GenerateCaller.callerFor(type, recorder());
            Assertions.assertFalse(caller instanceof DefaultFunctionCaller, service);
            checkStates(type, caller, 10);
        }
    }

    /**
     * The looped fallback must answer exactly what the generated one answers, or a downstream module that
     * sees both silently changes behaviour with globs.builder.
     */
    @Test
    public void theLoopedCallerAndTheGeneratedOneAgree() {
        for (String service : List.of(OBJECT, PRIMITIVE)) {
            for (int count : new int[]{10, 45}) {
                GlobType type = build(service, "CallerSame" + service.hashCode() + "_" + count, count);
                Field[] fields = type.getFields();
                MutableGlob glob = type.instantiate();
                IntStream.range(0, count).filter(i -> i % 3 == 0)
                        .forEach(i -> glob.setValue(fields[i], null));
                IntStream.range(0, count).filter(i -> i % 3 == 1)
                        .forEach(i -> glob.setValue(fields[i], sample(fields[i])));

                Assertions.assertEquals(call(new DefaultFunctionCaller<>(type, recorder()), glob),
                        call(callerOf(type), glob), service + " on " + count + " fields");
            }
        }
    }

    /**
     * The whole point : one static final field per field of the type, so every call site has a constant
     * receiver rather than the single megamorphic one a loop over the functions would give.
     */
    @Test
    public void theFunctionsAreHeldInStaticFinalFieldsOfAFreshClassPerCaller() throws Exception {
        GlobType type = build(OBJECT, "CallerStatics", 6);
        GeneratedFunctionCaller<List<Seen>, String> caller = callerOf(type);

        Class<?> generated = caller.getClass();
        Assertions.assertTrue(GeneratedFunctionCaller.class.isAssignableFrom(generated));
        Assertions.assertEquals("call", generated.getDeclaredMethod("call",
                org.globsframework.core.model.Glob.class, Object.class, Object.class).getName(),
                "call must be declared, not inherited from the interface");
        for (int i = 0; i < 6; i++) {
            java.lang.reflect.Field fn = generated.getDeclaredField("fn_" + i);
            Assertions.assertEquals(FieldValueFunction.class, fn.getType());
            Assertions.assertTrue(java.lang.reflect.Modifier.isStatic(fn.getModifiers()));
            Assertions.assertTrue(java.lang.reflect.Modifier.isFinal(fn.getModifiers()));
        }

        Assertions.assertNotSame(generated, callerOf(type).getClass(),
                "a second caller over the same type gets its own class, or they share call sites again");
    }

    /** The caller must agree with the Glob it is given, field by field and state by state. */
    @Test
    public void callerAgreesWithTheGlob() {
        for (String service : List.of(OBJECT, PRIMITIVE)) {
            for (int count : new int[]{10, 45}) {
                GlobType type = build(service, "CallerAgree" + service.hashCode() + "_" + count, count);
                GeneratedFunctionCaller<List<Seen>, String> caller = callerOf(type);
                Field[] fields = type.getFields();

                MutableGlob glob = type.instantiate();
                IntStream.range(0, count).filter(i -> i % 3 == 0)
                        .forEach(i -> glob.setValue(fields[i], null));
                IntStream.range(0, count).filter(i -> i % 3 == 1)
                        .forEach(i -> glob.setValue(fields[i], sample(fields[i])));

                List<Seen> seen = call(caller, glob);
                for (Field field : fields) {
                    Seen s = of(seen, field.getName());
                    Assertions.assertEquals(glob.isSet(field), s.isSet(), field.getName() + " isSet");
                    Assertions.assertEquals(glob.getValue(field) == null, s.isNull(), field.getName() + " isNull");
                    Assertions.assertEquals(glob.getValue(field), s.value(), field.getName() + " value");
                }
            }
        }
    }

    private Object sample(Field field) {
        return switch (field.getName().charAt(0)) {
            case 's' -> "v" + field.getIndex();
            case 'i' -> field.getIndex();
            case 'd' -> field.getIndex() + 0.5;
            default -> (long) field.getIndex();
        };
    }
}
